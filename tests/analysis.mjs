import assert from 'node:assert/strict';
import {createUI,response} from './ui-harness.mjs';
const ui=await createUI(({body})=>response(body.input.length===1?'分析結果 <img src=x onerror=alert(1)>':'追加質問への回答'));
ui.run("openDetail('1301')");
await ui.run('startAnalysis()');
assert.equal(ui.calls.length,1);
assert.equal(ui.el('analysisPanel').hidden,false);
assert.equal(ui.el('analyzeBtn').disabled,false);
assert.match(ui.el('analysisMessages').children[1].textContent,/<img src=x/);
assert.equal(ui.el('analysisMessages').children[1].innerHTML,'');
assert.match(ui.calls[0].body.instructions,/"code":"1301"/);
assert.match(ui.calls[0].body.instructions,/2026-10-30/);
assert.equal(ui.calls[0].body.instructions.includes('test-key'),false);
assert.equal(ui.calls[0].body.text,undefined);
ui.el('analysisQuestion').value='配当の注意点は？';
await ui.run('submitAnalysisQuestion()');
assert.equal(ui.calls[1].body.input.length,3);
assert.equal(ui.calls[1].body.input[1].role,'assistant');
assert.equal(ui.calls[1].body.input[2].content,'配当の注意点は？');
assert.equal(ui.el('analysisQuestion').value,'');
ui.el('analysisQuestion').value='前の銘柄の未送信質問';
ui.run("openDetail('1302')");
assert.equal(ui.el('analysisQuestion').value,'');
assert.equal(ui.el('analysisMessages').children.length,0);
ui.run("openDetail('1301')");
await ui.run('startAnalysis()');
assert.equal(ui.calls.length,2);
assert.equal(ui.el('analysisMessages').children.length,4);
const noKey=await createUI(()=>{throw Error('API must not be called');},{keys:{}});
noKey.run("openDetail('1301')");
assert.equal(noKey.el('analyzeBtn').disabled,true);
await noKey.run('startAnalysis()');
assert.equal(noKey.calls.length,0);
noKey.el('apiKey').value='saved-key';noKey.run('saveKey()');
assert.equal(noKey.el('analyzeBtn').disabled,false);
let finish;
const race=await createUI(()=>new Promise(resolve=>{finish=()=>resolve(response('古い銘柄の回答'));}));
race.run("openDetail('1301')");
const pending=race.run('startAnalysis()');
assert.equal(race.el('analysisSend').disabled,true);
race.run("openDetail('1302')");
assert.equal(race.calls[0].options.signal.aborted,true);
finish();await pending;
assert.equal(race.el('analysisMessages').children.length,0);
const failed=await createUI(()=>({ok:false,status:403,json:async()=>({error:{message:'insufficient permissions'}})}));
failed.run("openDetail('1301')");
await failed.run('startAnalysis()');
assert.match(failed.el('analysisError').textContent,/insufficient permissions/);
assert.equal(failed.el('analyzeBtn').disabled,false);
console.log('分析・追加質問の履歴・キー設定・銘柄切替・中断・失敗からの復帰 OK');
