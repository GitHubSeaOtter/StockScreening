import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),C=require('../docs/chart-interaction.js');
const data={dates:['2026-10-28','2026-10-29','2026-10-30'],close:[100,110,121],previousClose:80,currency:'USD'};
assert.equal(C.pointAt(data,0).dayPct,25);
assert.ok(Math.abs(C.pointAt(data,1).periodPct-10)<1e-9);
assert.equal(C.pointAt(data,500).index,2);
assert.equal(C.pointAt({...data,previousClose:null},0).dayPct,null);
const auto=C.layout(data.close),zero=C.layout(data.close,true);
assert.ok(auto.high>121);assert.ok(auto.low<100);assert.equal(zero.low,0);assert.ok(zero.high>121);
assert.ok(auto.y(121)>auto.top);assert.ok(auto.y(121)-4>0);
assert.ok(zero.y(121)>zero.top);assert.ok(zero.y(121)-4>0);
for(const close of [[100,100,100],[0,0],[0.001,0.001]]){
  const g=C.layout(close);assert.ok(g.high>g.low);assert.ok(Number.isFinite(g.y(close[0])));
}
const make=()=>({attrs:{},setAttribute(k,v){this.attrs[k]=v;}});
const x=make(),y=make(),dot=make(),fields={};
for(const key of ['date','price','day','period'])fields[key]={textContent:'',className:''};
const readout={querySelector:s=>fields[s.match(/point-(.*)\]/)[1]]};
const group={style:{display:'none'},querySelector:s=>s==='.cross-x'?x:s==='.cross-y'?y:dot};
const events={},svg={...make(),addEventListener:(name,fn)=>events[name]=fn,getBoundingClientRect:()=>({left:10,width:640}),setPointerCapture(){}};
const root={querySelector:s=>s==='svg.chart'?svg:s==='.chart-cross'?group:readout};
C.bind(root,data);
events.pointerdown({clientX:330,pointerId:1});
assert.equal(x.attrs.x1,160);assert.equal(y.attrs.y1,auto.y(110));
assert.equal(fields.date.textContent,'2026-10-29');assert.equal(fields.price.textContent,'110.00 USD');
assert.equal(fields.day.textContent,'+10.00%');assert.equal(fields.day.className,'pos');assert.equal(group.style.display,'');
events.pointermove({clientX:9999});assert.equal(x.attrs.x1,312);
events.keydown({key:'Home',preventDefault(){}});assert.equal(x.attrs.x1,8);
assert.equal(fields.day.textContent,'+25.00%');
C.bind(root,{...data,zeroBased:true});
events.pointerdown({clientX:330,pointerId:1});
assert.equal(x.attrs.x1,160);assert.equal(y.attrs.y1,zero.y(110));assert.ok(y.attrs.y1<auto.y(110));
console.log('チャートの余白・ゼロ起点・十字線の座標一致・読み取りカード OK');
